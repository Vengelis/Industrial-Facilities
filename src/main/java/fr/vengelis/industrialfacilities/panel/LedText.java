    private static void glyph(char c, String rows) {
        GLYPHS.put(c, Arrays.stream(rows.split("/")).mapToInt(s -> Integer.parseInt(s, 2)).toArray());
    }
    public static String normalize(String s) {
        return Normalizer.normalize(s.replace("œ","oe").replace("Œ","OE").replace('’','\'').replace('–','-').replace('—','-'),
            Normalizer.Form.NFD).replaceAll("\\p{M}", "").toUpperCase(Locale.ROOT);
    }
    private final String text;
    public LedText(String text) { this.text = normalize(text); }
    public static int scale(int height) { return height == 1 ? 1 : 2; }
    private static int verticalScale(int height) { return height == 1 ? 1 : height+1; }
    public int period(int height) { return text.length()*6*scale(height)+8; }
    /** x/y are global LED cell coordinates, counted from the top-left of the display. */
    public boolean lit(int x, int y, int height, long ticks, boolean right) {
        if (text.isEmpty()) return false;
        int scale = scale(height), vertical = verticalScale(height), yy = y-(height*16-7*vertical)/2;
        if (yy<0 || yy>=7*vertical) return false;
        int period = period(height);
        int shift = (int)Math.floorMod(ticks/2, (long)period);
        int xx = Math.floorMod(x+(right ? -shift : shift), period);
        if (xx>=text.length()*6*scale || xx/scale%6 == 5) return false;
        int[] glyph = GLYPHS.getOrDefault(text.charAt(xx/(6*scale)), GLYPHS.get('?'));
        return (glyph[yy/vertical] & (1 << (4-xx/scale%6))) != 0;
    }
